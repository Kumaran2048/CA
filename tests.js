import { Memory } from './src/modules/memory/Memory.js';
import { Assembler8085 } from './src/modules/assembler/Assembler8085.js';
import { CPU8085 } from './src/modules/cpu8085/CPU8085.js';
import { Assembler8086 } from './src/modules/assembler/Assembler8086.js';
import { CPU8086 } from './src/modules/cpu8086/CPU8086.js';

function runTests() {
  console.log('=== Starting Microprocessor Simulation Unit Tests ===');

  // Test 1: 8085 Assembly & Execution (Addition)
  const mem8085 = new Memory();
  const asm8085 = new Assembler8085();
  const cpu8085 = new CPU8085(mem8085);

  const prog8085 = `
    MVI B, 05H
    MVI C, 03H
    MOV A, B
    ADD C
    STA 2500H
    HLT
  `;

  const asmRes8085 = asm8085.assemble(prog8085, 0x2000);
  if (!asmRes8085.success) {
    throw new Error('8085 Assembler failed: ' + JSON.stringify(asmRes8085.errors));
  }
  console.log('[PASS] 8085 Two-Pass Assembly generated bytes:', asmRes8085.machineCode.map(b => b.toString(16).padStart(2,'0').toUpperCase()).join(' '));

  mem8085.loadProgram(0x2000, asmRes8085.machineCode);
  cpu8085.reset(0x2000);

  let steps = 0;
  while (!cpu8085.isHalted && steps < 100) {
    cpu8085.step();
    steps++;
  }

  const storedVal = mem8085.readByte(0x2500);
  console.log(`[PASS] 8085 CPU Executed in ${steps} steps. Accumulator: ${cpu8085.A}, Memory[0x2500]: ${storedVal}`);
  if (storedVal !== 8) {
    throw new Error(`Expected 8 at 0x2500, got ${storedVal}`);
  }

  // Test 2: 8086 Assembly & Execution (ADD & MUL)
  const mem8086 = new Memory();
  const asm8086 = new Assembler8086();
  const cpu8086 = new CPU8086(mem8086);

  const prog8086 = `
    MOV AX, 0005H
    MOV BX, 0003H
    ADD AX, BX
    HLT
  `;

  const asmRes8086 = asm8086.assemble(prog8086, 0x0100);
  if (!asmRes8086.success) {
    throw new Error('8086 Assembler failed: ' + JSON.stringify(asmRes8086.errors));
  }
  console.log('[PASS] 8086 Assembler generated bytes:', asmRes8086.machineCode.map(b => b.toString(16).padStart(2,'0').toUpperCase()).join(' '));

  mem8086.loadProgram(0x0100, asmRes8086.machineCode);
  cpu8086.reset(0x0100);

  let steps8086 = 0;
  while (!cpu8086.isHalted && steps8086 < 100) {
    cpu8086.step();
    steps8086++;
  }

  console.log(`[PASS] 8086 CPU Executed in ${steps8086} steps. AX: 0x${cpu8086.AX.toString(16).toUpperCase()}`);
  if (cpu8086.AX !== 0x0008) {
    throw new Error(`Expected AX=0x0008, got 0x${cpu8086.AX.toString(16)}`);
  }

  console.log('=== All Simulation Engine Unit Tests Passed Successfully! ===');
}

runTests();

